# 按角色选取最相关的类象维度
ROLE_KEY_CATEGORIES = {
    "体": ["性情", "人事", "身体", "方位"],
    "用": ["人物", "动物", "人事", "器物"],
    "互": ["人事", "性情", "器物", "动物"],
    "变": ["方位", "季节时令", "人事", "性情"],
}


def get_xiang_summary(trigram_num: int, role: str) -> str:
    """根据卦的角色(体/用/互/变)返回精简的类象摘要"""
    xiang = XIANG_DATA.get(trigram_num, {})
    categories = xiang.get("categories", {})
    keys = ROLE_KEY_CATEGORIES.get(role, ["性情", "人事"])

    parts = []
    for k in keys:
        if k in categories:
            parts.append(f"{k}：{categories[k]}")

    return "；".join(parts) if parts else ""
